// Passport launched 2026-10-03. One mystery country a day, played five ways
// (landmark, flag, borders, capital, numbers), one score out of 50, and the
// run ends on the passport that score earns. The bank (app/passport/days.js,
// generated by scripts/gen-passport.mjs) is resolved HERE, on the server, and
// only the picked day ships to the browser, so tomorrow's country never
// reaches a client. The landmark photo comes from /api/passport/img, keyed by
// puzzle number and refused for a day that is not yet live, and the Commons
// title is stripped here because it usually names the place.

// FROM 2026-10-15 (owner, 2026-10-14) a day is a RUN: the day's Span, Flank
// and Ping on this page, then nine bigger-or-smaller calls on the countries
// they were about (lib/passport-run.js). A light-index entry with v: 2 is a
// run day; the five-round days before it still play through PassportClient,
// from days.js, for the archive.

// THE LINK PREVIEW IS THE RUN'S OWN (owner, 2026-10-03): a pasted link
// unfurls with /passport/card, the departures board and the six passports,
// never the generic daily-puzzle card. A shared result link carries the five
// round scores (?s=10-7-8-9-6), so its preview shows the passport they
// earned; the page itself ignores the parameter.
export async function generateMetadata({ searchParams }) {
  const s = String((searchParams && searchParams.s) || '');
  const ok = /^\d{1,2}(-\d{1,2}){3,4}$/.test(s);
  const img = ok ? `/passport/card?s=${s}` : '/passport/card';
  const title = 'Passport: A Daily Geography Run | Mind Loft';
  const description = 'A free daily geography run: the day\'s Ping, nine bigger-or-smaller size calls, then Flank and Span. Score out of 50 and earn a passport.';
  const shareTitle = 'Passport · Mind Loft';
  const shareDesc = 'Ping, nine size calls, Flank and Span, one score out of 50. Which passport do you travel home on?';
  return {
    title, description,
    alternates: { canonical: '/passport' },
    openGraph: { title: shareTitle, description: shareDesc, url: '/passport', type: 'website', siteName: 'Mind Loft', images: [{ url: img, width: 1200, height: 630, alt: 'Passport, a daily geography run from Mind Loft' }] },
    twitter: { card: 'summary_large_image', title: shareTitle, description: shareDesc, images: [img] },
  };
}

