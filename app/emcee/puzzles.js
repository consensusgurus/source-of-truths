// Puzzle data for Emcee, the daily mini crossword. Imported ONLY by the
// server page (app/emcee/page.js), which filters live<=today before passing
// puzzles to the client — so future grids, and their answers, never ship to
// the browser (same gating as every other daily).
//
// Each puzzle: `grid` rows use '#' for a block and the SOLUTION letter for a
// fillable square (today's answers ship, like every daily). `across`/`down`
// carry {n, r, c, len, clue}; answers are read off the grid, and numbering
// follows standard crossword rules (validated by the generator). Weekdays are
// a 5x5 with 10 words; Sundays step up to a 7x7 pinwheel with 22. Score is
// words correct out of the word count — a full clean solve is score = total —
// with ties broken by fewest checks (guessesUsed) and then fastest time.
//
// ── AUTHORING RULES (added 2026-08-12 after a bad bulk extension) ──────────
//
// 1. EVERY CLUE IS HAND-WRITTEN AND CLUES ITS OWN ANSWER. Clues come from the
//    curated bank in scripts/emcee-wordbank.txt (WORD|clue, one per line), so
//    a word can only enter a grid if a real crossword clue exists for it.
//    NEVER generate a clue from a dictionary/WordNet gloss. The bulk batch
//    that filled 2026-08-11 → 2026-09-29 did exactly that and, because a
//    gloss defines a whole synonym set, it repeatedly clued the wrong word:
//    CUE was clued "Evidence that helps to solve a problem" (that is CLUE),
//    ACRES got the gloss of DEMESNE, PAR the gloss of PARITY, PEG the gloss
//    of LAND, PET the gloss of FAVORITE. Players read it as letters missing
//    from the words. Rebuilt 2026-08-12 from #28 on; #1–#27 are frozen.
// 2. GRIDS ARE FULLY CHECKED. Every white square belongs to BOTH an across
//    and a down word, so there are no 1-letter runs. On a 5x5 that means each
//    row and each column holds exactly one run, of length >= 2, which is what
//    gives exactly 10 words. #24 and #26 predate the rule and are grandfathered.
// 3. NO OBSCURITIES. Everyday words only. The old batch shipped ATE (the Greek
//    goddess), GRAD (one-hundredth of a right angle) and ORE (a Scandinavian
//    monetary subunit) — none of which belong in a one-minute mini.
// 4. VARIETY IS CAPPED ACROSS THE BANK, not just per board: an answer appears
//    at most 3 times, two boards share at most 2 answers (3 between two
//    Sundays, which carry 22 each), and no grid shape repeats within a week.
//    The verifier counts weekday grid shapes and caps them at 4 uses; it does
//    NOT cap Sunday shapes, so the generator holds its own ceiling there — a
//    Sunday shape at most 3 times per run and never two Sundays running.
// 5. THE PAST IS FROZEN. Never rewrite a board that has already gone live.
//
// Regenerate with `node scripts/build-emcee-bank.mjs`; verify with
// `node scripts/verify-daily-banks.mjs emcee`, which enforces 1, 2 and 4.
// EXTEND (append-only, leaves every banked board untouched, which is what you
// almost always want) with `node scripts/gen-emcee.mjs --write`. Its header
// carries the shape enumerations and the one number that governs how far this
// bank can run: a Sunday spends eighteen 3-letter answers, and no 22-word 7x7
// exists that spends fewer, so 3-letter clue entries are the whole runway.
