// page (app/mate/page.js), which filters live<=today before handing the bank to
// the client, so tomorrow's position and its solution never ship to the browser.
//
// Each puzzle is a position with WHITE TO MOVE and White forcing checkmate in
// `mateIn` moves. Weekdays are mate in two; Sundays step up to mate in three.
//
//   fen       full FEN. Castling is always '-', en passant always '-', and no
//             pawn ever stands on rank 1, 2, 7 or 8, which is what lets the
//             game's small engine (app/mate/chess.js) skip castling and en
//             passant entirely. Promotion is NOT skipped: a pawn on rank 6
//             reaches rank 8 inside a weekday budget, ten boards here can, and
//             the engine promotes to a queen. See that file's header.
//   solution  the FULL game tree, in UCI. `key` is White's only winning first
//             move; `lines` maps EVERY legal black reply to White's answer.
//             A node is either { move, lines } (play on) or { mate } (this move
//             is checkmate). Black's replies are looked up here at play time, so
//             a missing reply would be a crash: the set of keys in `lines` is
//             asserted to equal the legal reply set exactly.
//   motif     the name of the mating pattern, revealed only after the solve.
//
// Every board was verified twice, by two independent solvers, to be checkmate in
// exactly `mateIn` (never fewer) with EXACTLY ONE key move that works, and the
// game's own engine was cross-checked against python-chess over 460,652
// positions with zero disagreements.
//
// AUTHORING RULES for every board from 2026-09-30 (num 63) on. Boards are built
// by `node scripts/gen-mate.mjs` -- read its header for how to run it. It
// samples small legal endgame material, searches for a forced mate in exactly
// `mateIn` with a unique key on its own fast core, and then re-proves every
// accepted board from the FEN alone with chess.js, the engine below, before
// writing it. What it guarantees, beyond the three structural promises above:
//
//   legality   both kings on the board and never adjacent; Black, who is not to
//              move, is not already in check, and White is not in check either;
//              at most one queen, two rooks, two knights and two bishops a side,
//              with a bishop pair on opposite colours, since anything else needs
//              a promotion this bank cannot have had; Black is never ahead on
//              material.
//   size       4 to 8 men, and a Sunday carries at least 6 of them.
//   width      at least 14 legal White first moves, so the key is found rather
//              than forced, and at least 3 legal Black answers to it (a Sunday,
//              at least 4). At most 16 boards in a generated run may sit on that
//              3-reply floor: a floor is not a target.
//   variety    counted across a whole generated run and capped: an exact `motif`
//              string at most 2 (verify-mate's own MOTIF_CEILING), a mating
//              pattern family at most 8, a key piece type at most 16, a key move
//              character (quiet, check, discovered check, capture, capturing
//              check) at most 34, a material signature at most 4, a mating piece
//              type at most 18, and a mating square at most 3. Dates are filled
//              in shuffled order so those ceilings do not make the run drift
//              from quiet keys in one month to captures in the next.
//   motif      written from the line MateClient's own pickReply will actually
//              show, and every clause in it is read off the final position
//              rather than asserted. It carries NO trailing period, because the
//              client renders `{PUZZLE.motif}.`; boards 40-62 predate that
//              observation and show a double stop on the reveal card.
