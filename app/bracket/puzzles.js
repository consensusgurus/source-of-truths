// so a sports axis was added: stadium capacity, MLB career home runs, MLB career
// strikeouts, NFL career passing yards, and all-time Olympic golds by country. The
// future stretch was resequenced at the same time so no metric lands within four days
// of itself and no broad family (area, height, sport) lands two days running.
//
// AS-OF NOTE: any board whose values move over time carries an `asOf` string, which the
// client renders as "figures as of <asOf>" on the play header and in the rules panel.
