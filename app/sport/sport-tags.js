const ASKS_THE_SPORT = /\bwhich (?:[a-z-]+ )?(?:sport|discipline)\b|\bin which sport\b|\bgoverning body of which\b/i;

export function sportTagFor(q) {
  if (!q) return '';
  const lane = q.cat === 'Everything Else' ? null : q.cat;
  const tag = lane || SPORT_TAG[q.id] || 'Other sports';
  if (tag === 'Other sports') return tag;
  const low = tag.toLowerCase();
  // A lane leaks only when a choice IS the lane ("NBA", "The NFL"); a sport
  // name leaks wherever it appears in a choice.
  const norm = (c) => String(c).toLowerCase().replace(/^the\s+/, '').trim();
  const leaks = ASKS_THE_SPORT.test(String(q.q || ''))
    || (Array.isArray(q.choices) && q.choices.some((c) => (lane ? norm(c) === low : String(c).toLowerCase().includes(low))));
  return leaks ? (lane ? 'Sports' : 'Other sports') : tag;
}
