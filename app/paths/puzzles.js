// Board data for Paths, the daily network puzzle. Imported ONLY by the server
// page (app/paths/page.js), which filters live<=today before handing the bank to
// the client, so tomorrow's cheapest network never ships to a browser.
//
// A board is a lattice of n x n dots. `terms` are node ids (id = y*n + x): the
// FIRST is the depot, the rest are towns. A lane between two neighbouring dots
// is priced in this order: it cannot be laid at all if its "a-b" key (low id
// first) is in `cliffs`, it is free if the key is in `rails`, it costs 3 if the
// key is in `bridges`, it costs 2 if BOTH of its ends stand on a ridge (both
// ids in `hills`), and 1 otherwise. `rx` is the river's column per row, used
// only to draw it: the river runs down the gap at x = rx[y] - 0.5 and steps
// sideways between rows, and every lane it cuts, horizontal or vertical, is in
// `bridges`, so the barrier is continuous and has no free gap.
//
// `par` is the EXACT cheapest network (perfect), proved by a Dreyfus-Wagner
// Steiner-tree solve over the whole lattice, and `sol` is one network that
// achieves it. Ties on plain ground are unavoidable on a lattice, since two
// staircases between the same dots always cost the same, so `sol` is "a"
// cheapest network, not "the" one. What IS forced on every banked board: every
// ridge lane and every crossing in `sol` is load-bearing, meaning banning it
// makes the best possible network strictly worse. `greedy` is what the obvious
// connect-the-nearest-town approach costs, for reference.
//
// `tier` is how hard the board is, and it follows the weekday:
//
//   1  Monday to Wednesday   9x9, eight towns, open ground and ridge and river
//   2  Thursday              9x9, eight towns, plus CLIFFS, lanes you cannot lay
//   3  Friday and Saturday   9x9, NINE towns, plus OLD TRACK, lanes that are free
//   4  Sunday Edition       13x13, ELEVEN towns, every element on one board
//
// Boards 1 and 2 shipped at launch, before the ramp existed, so they are tier 1
// on a Thursday and a Friday. Every board after them follows its weekday.
//
// POOL VARIETY. Everything above is a rule about ONE board, and a bank of a
// hundred nine-town lattices can satisfy all of it while being the same puzzle
// wearing different coordinates every day. So from 2026-10-05 on there are
// ceilings across the whole run as well, enforced while boards are generated
// and re-checked by the verifier (`PATHS_VARIETY_FROM` in both files):
//
//   * no two boards anywhere in the bank share a river (`rx`), a ridge
//     footprint (`hills`) or a town set (`terms`);
//   * within a tier, at most 40% of the boards in scope may share the same
//     `par`, the same greedy-over-par gap, or the same river start column, and
//     at most 40% may sit EXACTLY on the tier's minimum gap - a floor is not a
//     target - while at most 50% may share a river jog count;
//   * at most 40% of boards in scope may put the depot in the same quadrant.
//
// Boards before 2026-10-05 are frozen history and out of scope, per the
// authoring standard's "the past is frozen".
//
// The bank is APPEND ONLY. scripts/gen-paths.mjs builds forward from the day
// after the last `live` date and never rewrites an existing board; there is no
// whole-bank regeneration mode, and that file's header says why not. Verify
// with scripts/verify-paths.mjs, which re-solves every board here from scratch
// and trusts none of this.
