// Puzzle data for Etch, the daily nonogram (picture logic). Imported ONLY by the
// server page (app/etch/page.js), which filters live<=today before handing the
// bank to the client, so future pictures never ship to the browser.
//
// Each puzzle is a w x h grid. `rows`/`cols` are the printed run-length clues
// (an empty line is [0]); `sol` is the answer, one string per row, '#' = filled.
// `subject` is what the finished picture shows, revealed only after the solve.
//
// Schedule, from 2026-08-18: Mon-Fri 10x10, Saturday 15x15, Sunday a 20x20
// Edition. Boards live before that date ran the older Sunday-only step-up
// (weekday 10x10, Sunday 15x15) and are FROZEN history, so scripts/verify-etch
// grandfathers them rather than resizing what people already played.
//
// Boards are generated by scripts/gen-etch.mjs from the shapes in
// scripts/etch-art.mjs (SMALL 10x10, MID 15x15, BIG 20x20); that script also
// owns the re-slotting, so do not hand edit dates or numbering here. Every
// board is verified by solver to have EXACTLY ONE solution AND to be reachable
// by pure line logic, with no guessing (scripts/verify-etch.mjs), so a careful
// solver never has to gamble.
//
// Authoring rules for the picture itself:
//   - A `subject` is the reveal, so it may be used ONCE in the whole bank, and
//     no two boards may share a solution grid. Both are checked.
//   - Variety is measured by kind, not just by repeat: every subject belongs to
//     one of twelve families (animals, plants, food, weather, transport,
//     buildings, tools, household, clothing, music, games, symbols) and no
//     family may hold more than 24 boards or 20% of the bank. The families are
//     listed in scripts/verify-etch.mjs and the ceiling is restated in the
//     header of scripts/etch-art.mjs.
//   - The picture has to READ at its size. A 10x10 subject must be legible as a
//     silhouette (an anchor, a cactus, a lighthouse), not something that needs
//     fine detail to identify; blobby shapes with long runs also solve cleanly,
//     while thin scattered detail tends to force a guess and fail the checks.
//   - Fill density is deliberately varied rather than pinned to one number
//     (10x10 boards run from 28 to 74 filled cells).
