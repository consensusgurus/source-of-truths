// Puzzle data for Check, the daily checkers shot. Imported ONLY by the server
// page (app/check/page.js), which filters live<=today before handing the bank to
// the client, so tomorrow's board and its key never reach a browser.
//
//   cells    64 digits, index row * 8 + col, row 0 at the TOP: 0 empty,
//            1 red man, 2 red king, 3 black man, 4 black king. You are red and
//            move up the board, crowning on row 0.
//   clearIn  how many of YOUR moves it takes to capture EVERY black piece
//            against black's stiffest defence. Three on weekdays, four on
//            Sundays, and never fewer than stated.
//   key      the one first move that does it, as the square path it travels.
//   blk      how many black pieces are on the board at the start.
//
// Every board was solved twice, by the shipping engine (app/check/draughts.js)
// and by an independent verifier that re-implements the rules on a different
// data structure with no memo table, and both agreed on the clear distance and
// on there being EXACTLY ONE winning first move. Every board additionally has
// no capture available at the start, so the key is a free choice rather than a
// forced jump, and on every board that key is a SACRIFICE: captures are
// compulsory in this game, so giving a piece away is how you pick black's reply
// for them.
//
// Boards from 2026-09-30 on are generated by scripts/gen-check.mjs, which holds
// three bars beyond the three above. Two are about the sacrifice being a real
// one: black has NO capture available BEFORE the key, so it is the key that
// hands the piece over rather than black having been about to jump anyway; and
// at least two of red's legal moves offer a piece, so the question is always
// WHICH sacrifice, never whether one exists. The third is what the end card
// promises -- black has exactly ONE legal answer to the key, so "offering a
// piece is how you choose black's reply for them" is literally true of the move
// the player finds. Red carries 2-5 pieces, black 2-4 on a weekday and 3-5 on a
// Sunday. Pool ceilings over a generated stretch: an exact key path at most
// twice (and at most three times bank-wide, which is the scope
// scripts/verify-check.mjs enforces), a starting shape -- red men/kings against
// black men/kings -- at most four times, and no more than 30% of the stretch on
// one key direction, 45% on one black-piece count, 45% on one red-piece count,
// or 40% on one red-MAN count. That last is the axis that collapses when nobody
// watches it: left to itself the search hands back an all-king red army on 55%
// of days, against 19% of the boards banked before this.
