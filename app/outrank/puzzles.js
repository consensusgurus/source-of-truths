//
// One themed slate a day. `items` is the DISPLAY order — hand-mixed, never the
// expected ranking, and never readable as the answer (from 2026-09-30 the
// verifier proves it is not the crowd order, not its reverse, never opens with
// the favorite, and moves at least three items two or more slots). Players tap a
// favorite (their vote) and then predict the crowd's full order of the slate by
// favorite-vote share. Sundays (`sunday: true`) run SEVEN items instead of six —
// keep that in sync with lib/sunday-editions.js.
//
// `house` IS AN AUTHORED ESTIMATE OF CROWD BEHAVIOR, NOT MEASURED PLAY. It is 40
// favorite votes (item indices) written by the author as a guess at how a broad
// audience would vote this slate, shaped by a vote ladder in
// scripts/gen-outrank.mjs. No real ballot has ever fed it, and nothing in the
// pipeline turns it into one. It exists only to give the day's first players a
// plausible field: it SEEDS the pool and then RETIRES, pool-wide, the moment an
// eleventh real player locks in (lib/outrank-score.js HOUSE_CUTOFF). From that
// player on, the crowd order is real votes and only real votes. If a board is
// ever seeded from real `outrank_picks` rows, say so on that board — this note
// does not cover it.
//
// AUTHORING RULES (checked by `node scripts/verify-daily-banks.mjs outrank`)
//   * Fresh, universally-known themes with a genuinely debatable order; a theme
//     is never reused. Culture-broad and family-readable: no slate should need
//     one country's supermarket to be playable, and none should need an adult.
//   * house always sums to 40 votes, leaves no item at zero, and gives every
//     item a DISTINCT count, so the crowd order is unambiguous. crowdOrderOf
//     breaks a tie on display index, and the display order carries no signal, so
//     a tie makes that boundary of the answer a coin toss. Boards #1 and #2 shipped
//     tied before the rule existed; they are frozen history and grandfathered.
//   * THE CROWD SHAPE, from 2026-09-30. The game only pays for insight if the
//     order is guessable but not obvious, so: favorite 11-14 of 40 on a weekday
//     and 8-12 on a Sunday, 2-5 clear of the runner-up, a tail of at least 2
//     (Sunday 1 — seven distinct counts summing to 40 cannot all clear 2), and
//     one to three adjacent boundaries exactly one vote apart on a weekday, two
//     to five on a Sunday. Every board carries a real close call; no board is
//     nothing but close calls.
//   * THE SUNDAY EDITION scales twice: seven items AND a crowd that is harder to
//     read (favorite capped two votes lower, at least two one-vote boundaries).
//   * VARIETY CEILINGS across the run, not per board: one theme category at most
//     8 of the 62 boards banked 2026-09-30 onward and never two days running;
//     one item string on at most 2 boards bank-wide; one house count vector on at
//     most 4 boards. The frozen bank is the warning — 32 of its 71 slates are
//     food or drink.
//   * US spellings in every reader-facing string (authoring standard #8).
//
