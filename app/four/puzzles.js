// Puzzle data for Four, the daily Connect Four position. Imported ONLY by the
// server page (app/four/page.js), which filters live<=today before handing the
// bank to the client, so tomorrow's board and its key never ship to a browser.
//
// Each puzzle is a real, reachable Connect Four position with YOU to move and a
// forced win. Weekdays are a win in four of your moves; Sundays step up to five.
//
//   cells      42 digits, column-major from the bottom of column 1: 0 empty,
//              1 yours (red), 2 the engine's (yellow). Index is col * 6 + row,
//              row 0 at the bottom.
//   key        the ONLY column that still wins. Every other drop throws the win
//              away, and unlike a refusal-style puzzle the game plays on: the
//              engine is perfect, so once the win is gone it never comes back.
//   rootScore  the solver's exact score for the key, in the engine's own units
//              (see app/four/c4.js): a win landing with S cells still empty
//              scores S, so the win is on ply (empty - S + 1).
//   winIn      how many of YOUR moves the forced win takes against best defense.
//   motif      the idea, revealed only after the game ends.
//
// Every position was solved twice, by the shipping engine and by an independent
// verifier that shares none of its pruning or hashing (app/four/c4.js versus the
// generator's second solver), and the two agreed on the score of every legal
// column. Each board was additionally checked to be legal and reachable (equal
// disc counts, no floating discs, no line of four already on the board), to have
// EXACTLY ONE winning column, and to force the win in exactly `winIn` moves
// against the engine's stubbornest defense, never fewer.
//
// FROM 2026-09-30 the boards are built by scripts/gen-four.mjs, which self-plays
// whole games and photographs the position rather than filling in a grid, so
// reachability is a property of the construction rather than an argument about
// it: the move list that produced each board is replayed and checked before the
// board ships. That generator also holds two authoring rules the earlier boards
// do not, both of them things scripts/verify-four.mjs cannot see:
//
//   * THE KEY IS THE ONLY COLUMN THAT STILL WINS, not merely the fastest. The
//     verifier checks that exactly one column holds the TOP score, which still
//     allows a second, slower win, and 11 of the boards before 2026-09-30 have
//     one. From 2026-09-30 on, every non-key column scores 0 or worse.
//   * THE ENGINE IS NOT ALREADY THREATENING at the root, so the key is never
//     merely the forced block. 20 of the boards before 2026-09-30 are that
//     shape. There are also at least 5 legal columns to choose between, 6 on a
//     Sunday, and a Sunday board carries at most 26 discs so the longer win has
//     more space behind it.
//
// Pool ceilings over that range, all stated and enforced in the generator: a
// key column at most 11 times in 62 and never on two days running; each disc
// count at most 14 times (weekday) or 4 times (Sunday) across 20/22/24/26/28/30,
// which is what spreads rootScore; each finishing direction at most 40% of the
// range; quiet keys and forcing keys each at most 62%; an opening's first eight
// plies at most twice; every generated motif string unique across the whole
// bank, well inside the verifier's own ceiling of 2; and no new board within 10
// differing cells of any other board in the bank, compared both straight and
// left-right mirrored, because a mirrored near-copy is the same puzzle.
