// no extra geometry to store: the diagonals are the same on every board.
//
// A DIAGONAL IS A HOUSE. Unlike Knight's eight squares, the nine cells of a
// diagonal all see each other and hold every digit, so hidden singles, locked
// candidates and subsets read off a diagonal exactly as off a row. There are
// 29 houses on this board, not 27.
//
// TWO MEASURED FIELDS, both recomputed by scripts/verify-diag.mjs rather than
// trusted:
//   printed  digits on the board. Mon 26, Tue 24, Wed 22, Thu 20, Fri 18,
//            Sat 16, and the Sunday Edition at 14, the fewest of the week.
//   level    the hardest technique the board demands: 1 naked and hidden
//            singles, 2 also locked candidates and naked/hidden subsets.
//            PINNED per weekday, not capped: Mon-Thu are always 1, Fri, Sat
//            and Sun always 2.
//
// EVERY board has EXACTLY ONE solution, reachable by logic with no guessing,
// and satisfies DIAGONAL NECESSITY: with the diagonals switched off the same
// clues admit more than one grid, so the rule is never decoration and a board
// can never be a plain sudoku in disguise. All of it is re-proved by the
