// A board is an ordinary 9x9 sudoku with ONE extra rule: no digit may repeat a
// chess knight's move away from itself, so a 5 forbids a 5 in the eight cells
// an L-shape away as well as in its row, column and box. `given` holds the
// printed clues (0 = a square the player fills) and `sol` the solution, used
// for the win check, the one hint, and reveal-and-end. There is no extra
// geometry to store: the knight relation is the same on every board.
//
// ⚠️ A KNIGHT SET IS NOT A HOUSE. The eight cells a knight's move away do not
// see each other, so they carry no "these cells hold every digit" guarantee.
// The rule supplies ELIMINATIONS ONLY, never a hidden single, a locked
// candidate or a subset. Rows, columns and boxes stay the only houses. Same
// trap Cages documents for cages.
//
// TWO MEASURED FIELDS, both recomputed by scripts/verify-knight.mjs rather
// than trusted:
//   printed  digits on the board. Mon 28, Tue 25, Wed 22, Thu 20, Fri 18,
//            Sat 16, and the Sunday Edition at 13, the fewest of the week.
//   level    the hardest technique the board demands: 1 naked and hidden
//            singles, 2 also locked candidates and naked/hidden subsets.
//            PINNED per weekday, not capped: Mon-Thu are always 1, Fri, Sat
//            and Sun always 2. Left as a ceiling, an 18-clue board comes out
//            singles-only two times in three, which is a Tuesday wearing
//            Friday's clue count.
//
// EVERY board has EXACTLY ONE solution, reachable by logic with no guessing,
// and satisfies KNIGHT NECESSITY: with the knight rule switched off the same
// clues admit more than one grid, so the rule is never decoration and a board
// can never be a plain sudoku in disguise. All of it is re-proved by the
// independent solvers in scripts/verify-knight.mjs, which shares no code with
// the generator.

