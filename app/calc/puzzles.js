// the server page (app/calc/page.js), which filters live<=today before handing
// puzzles to the client, so future boards never reach a browser.
//
// A board is an n x n CHECKERBOARD of buttons: (row + col) EVEN is a number 1-9,
// ODD is one of + - * /. A route runs from cell 0 (top-left) to cell n*n-1
// (bottom-right), stepping only to a touching cell, using no cell twice, and
// evaluating LEFT TO RIGHT like a calculator. A division that does not come out
// whole is not a legal step at all, which is what keeps every running total an
// integer.
//
// FIELDS, all recomputed by scripts/verify-calc.mjs rather than trusted:
//   cells        the board, row-major, as strings.
//   boardRoutes  how many legal routes the whole board has, corner to corner.
//   targets      the day's target(s). Each carries:
//                  target   the number the route has to come out at.
//                  routes   how many of the board's legal routes reach it.
//                  minLen   buttons in the SHORTEST route that reaches it.
//                  path     one such shortest route, for the hint and the reveal.
//
// DIFFICULTY IS TWO DIALS, and the grid is the lesser one. `routes` is the ramp:
// roughly 40-400 on a Monday down to 2-7 on a Saturday, out of tens of thousands
// of legal routes either way. `minLen` is capped per weekday because without a
// cap the search happily returns unique targets needing a 27-button snake, which
// nobody finds by hand.
//
// Weekday shape: Mon-Wed 6x6, Thu-Sat 7x7, and the SUNDAY EDITION is a 7x7 with
// THREE targets on the one board, easiest first. Weekday bands (routes /
// shortest route): Mon 40-400 / <=13, Tue 15-39 / <=13, Wed 5-14 / <=15,
// Thu 25-300 / <=15, Fri 8-24 / <=17, Sat 2-7 / <=17, Sun 25-300 / <=17 then
// 8-24 / <=19 then 1-4 / <=19.
//
