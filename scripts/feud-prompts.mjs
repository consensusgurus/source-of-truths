//   cat    one of the twenty categories below. No two prompts on one board may
//          share a category, and a category fills at most 22 of the 310.
//   shape  the crowd shape the author expects: 'steep' (a runaway favorite,
//          "Name a food people eat at a ball game"), 'flat' (the crowd genuinely
//          splits, "Name a way people relax"), 'mid' for everything between.
//          gen-feud.mjs picks a 40-vote ladder from that family.
//   q      the survey question. Opens "Name ...", ends in a full stop, never
//          repeats a prompt already in the bank.
//   a      the answer buckets, MOST POPULAR FIRST — that order is what the
//          house ladder is laid over, so it is load-bearing, not cosmetic.
//          Each is [display label, [alias keys]]. The label is matched too, so
//          the alias list only needs the VARIANTS.
//
// HOW TO WRITE THE ALIAS LIST (this is the craft; the rest is bookkeeping)
// The matcher is rules, not AI: lib/feud-match.js normalizes, stems, applies a
// fixed synonym table, and scores tokens. Ask "what would a real player type?"
// and write down every form the rules do NOT already reach. You get free:
//   plurals and -ing/-ed        keys / key, scrolling / scroll
//   filler words                "the fridge", "my keys", "I just read a book"
//   compound spacing            "chap stick" -> "lipbalm", "ear buds" -> "earbud"
//   one-character typos         "melatonan", "lasagne", "spagetti" (5+ letters)
//   one shared synonym table    tv/television, soda/pop/coke, sofa/couch,
//                               fridge/refrigerator, kid/child, mom/mum, ...
// You get NOTHING else. "Duvet" does not reach "Comforter". "The bill" does not
// reach "The check". "AC" does not reach "Air conditioning" unless the phrase
// table happens to cover it. Every one of those is an alias or a lost point.
//
// AND THE OTHER HALF: an alias must not reach a SIBLING bucket. Two buckets on
// one prompt that share a head noun, or where one's words sit inside the other's,
// are the same bucket to the matcher. The rule that avoids all of it is simply
// "no two buckets on one prompt share a content word", and gen-feud.mjs both
// warns on shared words and hard-fails on an actual collision.
