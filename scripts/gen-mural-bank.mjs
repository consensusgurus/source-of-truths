// scripts/gen-mural-bank.mjs: writes the day lists for Mural and MuralToo.
//   node scripts/gen-mural-bank.mjs [--until 2027-12-31]
//
// A mural has no authored board: the server picks and grades its photo when it
// opens (lib/mural.js). But both are registered dailies, and every daily roster
// (the slate maps, the archive, the day counts) reads a puzzles.js with one row
// per Eastern day. So this writes rows that carry only the day: num, quizId,
// live, dateLabel. The quizId is the SITE day (midnight to midnight Eastern)
// that a player's Mural points are filed under by mural_credit() (migration 70).
// Rows are append-only: an existing file is kept byte for byte and extended.
import fs from 'fs';
const arg = process.argv.indexOf('--until');
const until = arg > 0 ? process.argv[arg + 1] : '2027-12-31';
const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
const KINDS = [
  { key: 'mural', name: 'Mural', first: '2026-11-19', runs: 'noon to noon Eastern' },
  { key: 'muraltoo', name: 'MuralToo', first: '2026-11-20', runs: 'midnight to midnight Eastern' },
];
for (const k of KINDS) {
  const rows = [];
  for (let d = new Date(k.first + 'T00:00:00Z'), n = 1; d.toISOString().slice(0, 10) <= until; d = new Date(d.getTime() + 86400000), n++) {
    const y = d.getUTCFullYear(), m = d.getUTCMonth() + 1, day = d.getUTCDate();
    rows.push(`  ${JSON.stringify({ num: n, quizId: `${k.key}-${m}-${day}-${String(y).slice(2)}`, live: d.toISOString().slice(0, 10), dateLabel: `${MONTHS[m - 1]} ${day}, ${y}` })},`);
  }
  const head = `// The day list for ${k.name}, the 4,000 piece jigsaw the whole site builds together
// (${k.runs}). GENERATED by scripts/gen-mural-bank.mjs; extend with
// \`node scripts/gen-mural-bank.mjs --until <date>\`. There is no board here:
// the server picks and grades each photo when it opens (lib/mural.js). A row is
// one SITE day, the Eastern day a player's ${k.name} points are filed under.
// Checked by scripts/verify-mural.mjs.
export const PUZZLES = [
`;
  fs.writeFileSync(new URL(`../app/${k.key}/puzzles.js`, import.meta.url), head + rows.join('\n') + '\n];\n');
  console.log(k.key, rows.length, 'days to', until);
}
