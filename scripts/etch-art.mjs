// Art source for every generated Etch board: SMALL (Mon-Fri 10x10), MID
// (Saturday 15x15) and BIG (the Sunday 20x20 Edition).
//
// A subject is described one of two ways:
//   add/cut  primitives in board space [0,n)x[0,n), supersampled 5x5 per cell
//            and thresholded at half coverage, so a curved silhouette is smooth
//            and exact by construction rather than hand-typed cell by cell;
//   grid     an explicit array of n strings ('#' filled, '.' empty), for
//            subjects whose readability lives in individual cells -- every
//            10x10, and the 15x15/20x20 subjects with limbs, beaks or rotors
//            that a rasterised curve rounds away.
// Exactly one of the two per entry. `name` is the reveal, so it is also the
// board's `subject`.
//
// Nothing here decides what ships. scripts/gen-etch.mjs rasterises these,
// derives the clues, and keeps only the boards that a nonogram line solver can
// finish with no guessing; scripts/verify-etch.mjs then re-proves that
// independently over the committed bank. A subject that fails is dropped, never
// nudged into passing by hand. Entries the calendar has not reached yet are
// marked "Runway" and simply sit in the pool until a future date needs them.
//
// POOL VARIETY CEILING (verify-etch caps repeats at zero -- no subject and no
// solution grid may appear twice -- but it does not police *kinds* of subject,
// so this file does). Across the whole bank every subject belongs to one of
// twelve families: animals & sea life, plants & produce, food & drink, nature
// sky & weather, transport & travel, buildings & structures, tools & hardware,
// household & furnishings, clothing & accessories, music, games toys & sport,
// symbols & heraldry. NO FAMILY MAY EXCEED 24 BOARDS OR 20% OF THE BANK,
// whichever is smaller. At 127 boards (through 2026-11-30) the largest family
// is animals & sea life at 19 (15.0%); household & furnishings is 16 and
// transport & travel 15. Anyone adding art here should recount before adding a
// third bird or a fourth truck.
const S = 5;

export const rect = (x0, y0, x1, y1) => (x, y) => x >= x0 && x < x1 && y >= y0 && y < y1;
export const ell = (cx, cy, rx, ry) => (x, y) => ((x - cx) / rx) ** 2 + ((y - cy) / ry) ** 2 <= 1;
export const poly = (pts) => (x, y) => {
  let inside = false;
  for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) {
    const [xi, yi] = pts[i], [xj, yj] = pts[j];
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
};
export const seg = (x0, y0, x1, y1, t) => (x, y) => {
  const dx = x1 - x0, dy = y1 - y0, L = dx * dx + dy * dy;
  let u = L ? ((x - x0) * dx + (y - y0) * dy) / L : 0;
  u = Math.max(0, Math.min(1, u));
  const px = x0 + u * dx, py = y0 + u * dy;
  return (x - px) ** 2 + (y - py) ** 2 <= (t / 2) ** 2;
};
const anyOf = (fs) => (x, y) => fs.some((f) => f(x, y));

export function raster(n, add, cut = []) {
  const A = anyOf(add), C = cut.length ? anyOf(cut) : () => false;
  const g = [];
  for (let r = 0; r < n; r++) {
    let row = '';
    for (let c = 0; c < n; c++) {
      let hit = 0;
      for (let sy = 0; sy < S; sy++) for (let sx = 0; sx < S; sx++) {
        const x = c + (sx + 0.5) / S, y = r + (sy + 0.5) / S;
        if (A(x, y) && !C(x, y)) hit++;
      }
      row += hit * 2 >= S * S ? '#' : '.';
    }
    g.push(row);
  }
  return g;
}

const keys = (y0, y1, xs) => xs.map((x) => rect(x, y0, x + 1, y1));

