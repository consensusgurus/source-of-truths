// scripts/gen-saw.mjs: deals the Saw bank (app/saw/puzzles.js) from the photo
// pool in scripts/saw-photos.mjs, one photo a day from LAUNCH (2026-11-06).
//
//   node scripts/gen-saw.mjs
//
// THE CUT IS TALL (owner, 2026-11-06): every Saw photo is a portrait picture,
// and the cut follows its shape. A photo between 1.30 and 1.42 times as tall as
// it is wide is cut 8 across by 10 down (80 pieces); a taller one, 7 by 11
// (77). Fewer columns than Jig's ten is what makes the pieces larger on a
// phone. The tab pattern is drawn by the client from `seed`.
//
// The deal is deterministic from the pool's ORDER: extend the bank by adding
// photos at the END of scripts/saw-photos.mjs. Never reorder or remove a row
// that has gone live.
import fs from 'fs';
import { PHOTOS } from './saw-photos.mjs';

export const LAUNCH = '2026-11-06';
export const cutFor = (w, h) => (h / w < 1.42 ? [8, 10] : [7, 11]);
const seedFor = (num) => (num * 6007 + 4211) % 100003;
const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

const d0 = new Date(LAUNCH + 'T12:00:00Z');
const rows = PHOTOS.map((p, i) => {
  const d = new Date(d0.getTime() + i * 86400000);
  const [cols, rows_] = cutFor(p.w, p.h);
  const num = i + 1;
  return {
    num,
    quizId: `saw-${d.getUTCMonth() + 1}-${d.getUTCDate()}-${String(d.getUTCFullYear()).slice(2)}`,
    live: d.toISOString().slice(0, 10),
    dateLabel: `${MONTHS[d.getUTCMonth()]} ${d.getUTCDate()}, ${d.getUTCFullYear()}`,
    cols, rows: rows_,
    seed: seedFor(num),
    t: p.t, name: p.name, lic: p.lic, by: p.by,
  };
});

const head = `// Puzzle data for Saw, the tall daily jigsaw. Generated by scripts/gen-saw.mjs
// from scripts/saw-photos.mjs; do not hand edit. One portrait Wikimedia Commons
// featured picture a day: \`t\` is the Commons file title (fetched only through
// /api/saw/img, which refuses a day not yet live), \`name\`, \`lic\` and \`by\`
// are printed on the finish card, \`cols\` x \`rows\` is the cut (8x10 or 7x11)
// and \`seed\` draws the tabs. The shared daily consumers read
// num/quizId/live/dateLabel. The server page strips future days.
export const PUZZLES = [
`;
if (process.argv[1] && process.argv[1].endsWith('gen-saw.mjs')) {
  fs.writeFileSync('app/saw/puzzles.js', head + rows.map((r) => '  ' + JSON.stringify(r) + ',').join('\n') + '\n];\n');
  console.log(`gen-saw: ${rows.length} boards, ${rows[0].live} to ${rows[rows.length - 1].live}`);
}
