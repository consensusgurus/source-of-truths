// scripts/gen-simon.mjs — writes app/simon/puzzles.js.
//
// Simon ships no board: the day's SEQUENCE is generated from the quizId by
// lib/simon-engine.js, in the client and in the verifier alike. A row carries
// only the frame (par), so this is a calendar walk and nothing more.
//
//   node scripts/gen-simon.mjs > app/simon/puzzles.js
//
// Deterministic. Re-running it on an unchanged calendar is byte-identical, and
// it never renumbers: day 1 is FIRST and every later row follows by date.
// Arcade plays the same every day (owner, 2026-10-25), so there is no Sunday
// frame and no `sunday: true` row.

const FIRST = '2026-11-07';
const LAST = '2027-03-31';
const PAR = 10;

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
const rows = [];
let d = new Date(FIRST + 'T12:00:00Z');
const end = new Date(LAST + 'T12:00:00Z');
let num = 1;
while (d <= end) {
  const y = d.getUTCFullYear(), m = d.getUTCMonth() + 1, day = d.getUTCDate();
  const live = `${y}-${String(m).padStart(2, '0')}-${String(day).padStart(2, '0')}`;
  rows.push(`  { num: ${num}, quizId: 'simon-${m}-${day}-${String(y).slice(2)}', live: '${live}', dateLabel: '${MONTHS[m - 1]} ${day}, ${y}', sunday: false, par: ${PAR} },`);
  num++;
  d = new Date(d.getTime() + 86400000);
}

process.stdout.write(`// Puzzle data for Simon, the daily repeat-the-sequence memory game. Imported
// ONLY by the server page (app/simon/page.js), which filters live<=today before
// handing the bank to the client. Generated by scripts/gen-simon.mjs; edit
// that, not this.
//
// Simon has no authored board: the day's SEQUENCE is generated in the client
// from \`quizId\` (lib/simon-engine.js dayPlan), so every player on a given day
// gets the same pads in the same order. A row therefore carries only the frame:
//
//   par   the day's BENCHMARK length, not a ceiling. The longest sequence
//         repeated is the score, posted raw and uncapped, and par is only the
//         denominator the combined board uses for its completion ratio (it
//         clamps at 1). Reaching par wins the end card. A starting estimate:
//         revisit once a fortnight of real scores exists.
export const PUZZLES = [
${rows.join('\n')}
];
`);
