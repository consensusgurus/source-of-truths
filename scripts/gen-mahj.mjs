// scripts/gen-mahj.mjs: deals the Mahj bank.
//
//   node scripts/gen-mahj.mjs            writes app/mahj/puzzles.js and
//                                        scripts/mahj-orders.json
//
// Every day is the full 144-tile set on that weekday's layout (lib/mahj-core.js
// LAYOUT_BY_DOW): Monday Bridge, Tuesday Fortress, Wednesday Cross, Thursday
// Towers, Friday Wide, Saturday Arena, and the classic Pyramid on Sunday, the
// Sunday Edition.
//
// SOLVABLE BY CONSTRUCTION. Each deal is built by dealOver(): walk a removal
// order over the empty layout, always taking two tiles free at that moment, and
// give each step a matching pair. That order clears the board when played
// forwards. It is written to scripts/mahj-orders.json, which never ships to a
// browser, and scripts/verify-mahj.mjs replays it with its own geometry.
//
// THE WEEK RAMPS BY MEASURED EASE. Each day deals CANDIDATES boards off its own
// seeds and measures each one's ease (lib/mahj-core.js easeOf: the mean share a
// random player clears before running out of open pairs, 40 seeded runs). The
// day takes the candidate at its weekday's quantile, gentlest Monday, hardest
// Sunday. Deterministic: re-running reproduces the bank byte for byte.
import fs from 'fs';
import {
  LAYOUTS, LAYOUT_BY_DOW, fullSet, dealOver, encodeDeal, easeOf, hash32, mulberry32,
} from '../lib/mahj-core.js';

const FIRST = '2026-10-25';
const LAST = '2027-01-31';
const CANDIDATES = 16;
// Quantile of the candidates sorted by ease, ascending (0 = the hardest).
const QUANTILE = [0, 1, 0.8, 0.65, 0.5, 0.35, 0.2];   // Sun .. Sat

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
const rows = [], orders = {};
let d = new Date(FIRST + 'T12:00:00Z');
const end = new Date(LAST + 'T12:00:00Z');
let num = 1;
while (d <= end) {
  const y = d.getUTCFullYear(), m = d.getUTCMonth() + 1, day = d.getUTCDate();
  const live = `${y}-${String(m).padStart(2, '0')}-${String(day).padStart(2, '0')}`;
  const dow = d.getUTCDay();
  const layout = LAYOUT_BY_DOW[dow];
  const quizId = `mahj-${m}-${day}-${String(y).slice(2)}`;
  const n = LAYOUTS[layout].pos.length;
  const all = Array.from({ length: n }, (_, i) => i);
  const cands = [];
  for (let c = 0; c < CANDIDATES; c++) {
    const rnd = mulberry32(hash32(`mahj-deal::${quizId}::${c}`));
    const dl = dealOver(layout, all, fullSet(), rnd);
    if (!dl) continue;
    const ease = easeOf(layout, dl.faces, hash32(`mahj-ease::${quizId}::${c}`));
    cands.push({ c, ease, dl });
  }
  if (!cands.length) throw new Error(`${quizId}: no deal`);
  cands.sort((a, b) => a.ease - b.ease || a.c - b.c);
  const pick = cands[Math.round(QUANTILE[dow] * (cands.length - 1))];
  rows.push(`  { num: ${num}, quizId: '${quizId}', live: '${live}', dateLabel: '${MONTHS[m - 1]} ${day}, ${y}', ${dow === 0 ? 'sunday: true, ' : ''}layout: '${layout}', ease: ${pick.ease.toFixed(3)},\n    deal: '${encodeDeal(pick.dl.faces)}' },`);
  orders[quizId] = pick.dl.order.map(([a, b]) => `${a}.${b}`).join(' ');
  process.stderr.write(`${quizId.padEnd(14)} ${layout.padEnd(9)} ease ${pick.ease.toFixed(3)} (of ${cands[0].ease.toFixed(3)}..${cands[cands.length - 1].ease.toFixed(3)})\n`);
  num++;
  d = new Date(d.getTime() + 86400000);
}

fs.writeFileSync(new URL('../app/mahj/puzzles.js', import.meta.url), `// Puzzle data for Mahj, the daily 144-tile mahjong solitaire. Imported ONLY by
// the server page (app/mahj/page.js), which filters live<=today before handing
// the bank to the client, so tomorrow's deals never reach a browser.
//
// GENERATED by scripts/gen-mahj.mjs and checked by scripts/verify-mahj.mjs.
// Do not hand edit.
//
//   layout  the day's layout (lib/mahj-core.js LAYOUTS), by weekday: Monday
//           Bridge, Tuesday Fortress, Wednesday Cross, Thursday Towers,
//           Friday Wide, Saturday Arena, Sunday Pyramid (the Sunday Edition)
//   ease    the measured share a random player clears before running out of
//           pairs (lib/mahj-core.js easeOf); the week ramps down it, gentlest
//           Monday to hardest Sunday
//   deal    144 characters, one face per layout position in the layout's
//           order (lib/mahj-core.js ALPHABET). Every deal is clearable by
//           construction; the clearing order lives in scripts/mahj-orders.json
//           and never ships
//   sunday  true on Sundays only: the Pyramid, the hardest deal of the week
export const PUZZLES = [
${rows.join('\n')}
];
`);
fs.writeFileSync(new URL('./mahj-orders.json', import.meta.url), JSON.stringify(orders, null, 0).replace(/","/g, '",\n"') + '\n');
console.error(`mahj: ${rows.length} days, ${FIRST} to ${LAST}`);
