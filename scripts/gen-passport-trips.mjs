// scripts/gen-passport-trips.mjs: generates app/passport/trips.js, the
// Passport TRIP bank (owner, 2026-11-06), from the schedule below. Run from
// the repo root:
//
//   node scripts/gen-passport-trips.mjs
//
// THE TRIP. From TRIP_FROM (lib/passport.js) a Passport day is one journey,
// and every leg is set up by the one before it:
//   1 Ping    find the secret city: it is where you depart from
//   2 Span    cross the map by land borders, from that city's country to the
//             day's destination
//   3 Flank   name every land neighbor of the destination you reached
//   4 Stamps  the capital of each country your road crossed, for its stamp
// The legs are RUN-ONLY boards: they file no row of their own and never touch
// the standalone Ping, Span or Flank pages, so playing those first spoils
// nothing here and the reverse.
//
// The schedule is hand-picked (city, destination, blurb); everything else is
// derived and checked here, and the script refuses to write a bank that breaks
// a rule:
//   - the city is in lib/ping-cities.js (so it is a valid Ping guess), in a
//     country with land borders, never a city the Ping bank has used, and
//     never repeated in this bank;
//   - perfect = BFS-minimum hops on app/span/borders.js; weekday 3 to 5,
//     Saturday 4 to 6, Sunday Edition 5 to 8;
//   - the destination is a Flank subject (not noSubject) whose Flank neighbor
//     set matches Span's graph exactly, so the country you arrive in and the
//     ring you are asked to name agree; weekday and Saturday 2 to 7 neighbors,
//     Sunday 6 or more; never the same day's standalone Span endpoint or
//     Flank country, and never repeated in this bank;
//   - the start country never repeats within 7 days.
// Days already live are regenerated byte-identical because everything is
// derived from the same frozen schedule (never edit a past day).

