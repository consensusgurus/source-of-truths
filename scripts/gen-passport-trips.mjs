const ADJ = buildAdj();
const CODE = Object.fromEntries(Object.entries(BORDERS).map(([c, v]) => [v.name, c]));
const CAP = Object.fromEntries(COUNTRIES.map((c) => [c.t, c.cap]));
const PING_USED = new Set(PING.map((p) => p.city));
const dow = (iso) => new Date(`${iso}T12:00:00Z`).getUTCDay();
const fail = (msg) => { console.error(`gen-passport-trips: ${msg}`); process.exit(1); };

// Number of distinct shortest roads, for the Span note.
function roadCount(from, to) {
  const dist = distancesFrom(ADJ, from);
  const ways = { [from]: 1 };
  const order = Object.keys(dist).sort((a, b) => dist[a] - dist[b]);
  for (const c of order) {
    if (c === from) continue;
    ways[c] = [...(ADJ[c] || [])].filter((n) => dist[n] === dist[c] - 1).reduce((t, n) => t + (ways[n] || 0), 0);
  }
  return ways[to] || 0;
}

const out = [];
const seenCity = new Set(), seenDest = new Set();
for (const [iso, city, country, dest, blurb] of SCHEDULE) {
  const pz = PASSPORT.find((p) => p.live === iso);
  if (!pz) fail(`${iso}: no Passport light-index day (extend app/passport/puzzles.js first)`);
  const c = CITIES.find((x) => x.name === city && x.country === country);
  if (!c) fail(`${iso}: ${city}, ${country} is not in lib/ping-cities.js`);
  if (PING_USED.has(city)) fail(`${iso}: ${city} is already a Ping answer`);
  if (seenCity.has(city)) fail(`${iso}: ${city} repeats`);
  seenCity.add(city);
  if (!ADJ[country] || !ADJ[country].size) fail(`${iso}: ${country} has no land borders on Span's graph`);
  if (!ADJ[dest]) fail(`${iso}: ${dest} is not on Span's graph`);
  const code = CODE[dest];
  if (!code || BORDERS[code].noSubject) fail(`${iso}: ${dest} is not a Flank subject`);
  const fl = BORDERS[code].n.map((x) => BORDERS[x].name).sort().join('|');
  const sp = [...ADJ[dest]].sort().join('|');
  if (fl !== sp) fail(`${iso}: ${dest}'s Flank ring (${fl}) differs from Span's (${sp})`);
  const sun = dow(iso) === 0, sat = dow(iso) === 6;
  const perfect = distancesFrom(ADJ, country)[dest];
  // LONGER ROADS (owner, 2026-11-06: "the span itself needs to be farther, more
  // countries in between", once the map showed the road): weekday 5 to 7,
  // Saturday 6 to 8, Sunday Edition 8 to 11.
  const [hl, hh] = sun ? [8, 11] : sat ? [6, 8] : [5, 7];
  if (!(perfect >= hl && perfect <= hh)) fail(`${iso}: ${country} to ${dest} is ${perfect} hops, outside ${hl}-${hh}`);
  const ring = BORDERS[code].n.length;
  if (sun ? ring < 6 : (ring < 2 || ring > 7)) fail(`${iso}: ${dest} has ${ring} neighbors, outside the ${sun ? 'Sunday' : 'weekday'} band`);
  if (seenDest.has(dest)) fail(`${iso}: destination ${dest} repeats`);
  seenDest.add(dest);
  const sp0 = SPAN.find((p) => p.live === iso), fl0 = FLANK.find((p) => p.live === iso);
  if (sp0 && (sp0.start === dest || sp0.end === dest)) fail(`${iso}: ${dest} is the standalone Span's endpoint that day`);
  if (fl0 && fl0.c === code) fail(`${iso}: ${dest} is the standalone Flank country that day`);
  const prev = out.slice(-7).find((t) => t.from === country);
  if (prev) fail(`${iso}: start ${country} repeats within 7 days (${prev.live})`);
  for (const n of [country, dest]) if (!CAP[n]) fail(`${iso}: no capital for ${n}`);
  const roads = roadCount(country, dest);
  // Country names that take "the" in running prose (review, 2026-11-12: the
  // 11-26 note read "from United States"). No live day carried one, so no
  // frozen note changes.
  const the = theCountry;
  const note = roads === 1
    ? `There is exactly one shortest road from ${the(country)} to ${the(dest)}: ${perfect} borders.`
    : `There are ${roads} shortest roads from ${the(country)} to ${the(dest)}, each ${perfect} borders long.`;
  if (/\u2014/.test(blurb + note)) fail(`${iso}: em dash in copy`);
  out.push({ num: pz.num, live: iso, sunday: sun, city, from: country, lat: c.lat, lng: c.lng, blurb, to: dest, perfect, note, c: code, a: [...BORDERS[code].n].sort((x, y) => BORDERS[x].name.localeCompare(BORDERS[y].name)) });
}

