#!/usr/bin/env node
// gen-kids-ladder: build app/kids/ladder/puzzles.js AND lib/kids-ladder-words.js.
//
// Ladder is Rung for kids: three-letter words, change one letter a step, climb
// from the start word to the end word. The vocabulary is the list below, every
// word one a young reader knows (no abbreviations, no names, US spellings), and
// it ships to the browser whole so the board can accept ANY real step, not
// only the setter's. Rules the bank keeps, re-checked by scripts/verify-kids.mjs:
//   - `best` is the true shortest ladder (BFS over the vocabulary), 3 or 4 on
//     weekdays, 5 on every seventh board (a slightly longer climb, never a wall)
//   - start and end share no letter position (so no step is free)
//   - no start or end word returns inside 20 boards; no pair ever repeats
//
//   node scripts/gen-kids-ladder.mjs [--days 60] [--seed 5]
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const argv = process.argv.slice(2);
const opt = (k, d) => { const i = argv.indexOf(k); return i >= 0 ? argv[i + 1] : d; };
const DAYS = +opt('--days', 60);
const SEED = +opt('--seed', 5);

