const uniq = [...new Set(WORDS)];
if (uniq.length !== WORDS.length) throw new Error('duplicate word in list');
for (const w of WORDS) if (!/^[a-z]{3}$/.test(w)) throw new Error(`bad word ${w}`);

export function neighbors(w, vocab) {
  const out = [];
  for (const v of vocab) {
    if (v === w) continue;
    let d = 0;
    for (let i = 0; i < 3; i++) if (v[i] !== w[i]) d++;
    if (d === 1) out.push(v);
  }
  return out;
}
export function shortest(a, b, vocab) {
  const prev = new Map([[a, null]]);
  const q = [a];
  while (q.length) {
    const w = q.shift();
    if (w === b) {
      const path = [];
      for (let x = b; x != null; x = prev.get(x)) path.unshift(x);
      return path;
    }
    for (const n of neighbors(w, vocab)) if (!prev.has(n)) { prev.set(n, w); q.push(n); }
  }
  return null;
}

function rng(seed) { let s = seed >>> 0 || 1; return () => { s = (s * 1664525 + 1013904223) >>> 0; return s / 4294967296; }; }
const rand = rng(SEED);
const pick = (arr) => arr[Math.floor(rand() * arr.length)];

const isMain = process.argv[1] && process.argv[1].endsWith('gen-kids-ladder.mjs');
const bank = [];
const usedPairs = new Set();
const lastEnd = new Map();
const GAP = 20;
for (let day = 1; isMain && day <= DAYS; day++) {
  const want = day % 7 === 0 ? 5 : (day % 2 === 0 ? 4 : 3);
  let found = null;
  for (let t = 0; t < 5000 && !found; t++) {
    const a = pick(WORDS);
    const b = pick(WORDS);
    if (a === b) continue;
    if ([0, 1, 2].some((i) => a[i] === b[i])) continue;
    const key = [a, b].sort().join('-');
    if (usedPairs.has(key)) continue;
    const la = lastEnd.get(a); const lb = lastEnd.get(b);
    if ((la != null && day - la < GAP) || (lb != null && day - lb < GAP)) continue;
    const path = shortest(a, b, WORDS);
    if (!path || path.length - 1 !== want) continue;
    found = { a, b, path, key };
  }
  if (!found) throw new Error(`day ${day}: no ladder of length ${want}`);
  usedPairs.add(found.key); lastEnd.set(found.a, day); lastEnd.set(found.b, day);
  bank.push({ num: day, start: found.a, end: found.b, best: found.path.length - 1, example: found.path });
}

const bankSrc = `// Ladder bank. GENERATED by scripts/gen-kids-ladder.mjs; do not edit by hand.
// \`best\` is the proven shortest climb over lib/kids-ladder-words.js and
// \`example\` one ladder that achieves it (shown after the climb, never before).
// The bank CYCLES over kids days (lib/kids-daily.js).
export const PUZZLES = [
${bank.map((b) => `  { num: ${b.num}, start: ${JSON.stringify(b.start)}, end: ${JSON.stringify(b.end)}, best: ${b.best}, example: ${JSON.stringify(b.example)} },`).join('\n')}
];
`;
const wordsSrc = `// Ladder vocabulary. GENERATED by scripts/gen-kids-ladder.mjs from the list in
// that file; do not edit by hand. Shipped to the browser so any real three-letter
// word is a legal rung, not only the setter's.
export const LADDER_WORDS = ${JSON.stringify(WORDS)};
export const LADDER_SET = new Set(LADDER_WORDS);
`;
if (isMain) {
  writeFileSync(join(here, '..', 'app', 'kids', 'ladder', 'puzzles.js'), bankSrc);
  writeFileSync(join(here, '..', 'lib', 'kids-ladder-words.js'), wordsSrc);
  console.log(`wrote ${bank.length} ladders over ${WORDS.length} words`);
}
