// scripts/verify-sudoclue.mjs: proves every Sudoclue case in app/sudoclue/puzzles.js.
//
// For each board: the place exists and is well formed (N by N rooms, every room
// named with a floor and a clue phrase, items inside the grid and inside one
// room, no object on another), the cast is N distinct names that all have a
// portrait, the dates run one a day with quizIds matching them, and the clues,
// solved by lib/sudoclue-engine.js, allow EXACTLY ONE answer: one placement and
// one role for everyone, and each STAGE stands alone: the placement clues fix the board by themselves and
// the role clues fix the roles on that board. The cases were generated by a separate Python search,
// so this is an independent re-check, not the generator grading itself.
//   node scripts/verify-sudoclue.mjs
import { PUZZLES } from '../app/sudoclue/puzzles.js';
import { PLACES } from '../lib/sudoclue-places.js';
import { solve, solvePlacement, solveRoles, ROLESETS, gradePlacement, gradeRoles, isRoleClue, DAY_BAND } from '../lib/sudoclue-engine.js';
import { CAST, OBJ } from '../lib/sudoclue-art.js';

let fail = 0;
const GRADED_FROM = 5;
// THREE ROLES, NOTES ONLY (owner, 2026-11-03) from No. 6 (Wed Nov 4): victim, killer, accomplice, nobody else.
const THREE_FROM = 6;
const bad = (m) => { fail++; console.log('✗ ' + m); };
const KINDS = new Set(['at', 'with', 'notwith', 'north', 'east', 'col', 'isrole', 'notrole', 'same', 'some', 'every', 'none', 'rrel', 'prel', 'count']);

for (const [key, L] of Object.entries(PLACES)) {
  const N = L.rooms.length;
  if (!ROLESETS[N]) bad(`${key}: no roleset for ${N}`);
  if (L.rooms.some((r) => r.length !== N)) bad(`${key}: rooms are not ${N} by ${N}`);
  for (const ch of new Set(L.rooms.join(''))) {
    const ri = L.rinfo[ch];
    if (!ri || !ri.name || !ri.floor || !ri.at) bad(`${key}: room ${ch} lacks name, floor or clue phrase`);
  }
  const seen = {};
  for (const it of L.items) {
    if (!OBJ[it.t]) bad(`${key}: ${it.t} has no drawing`);
    for (let dr = 0; dr < it.h; dr++) for (let dc = 0; dc < it.w; dc++) {
      const r = it.r + dr, c = it.c + dc, k = `${r},${c}`;
      if (r >= N || c >= N) bad(`${key}: ${it.t} runs off the board`);
      else if (L.rooms[r][c] !== L.rooms[it.r][it.c]) bad(`${key}: ${it.t} straddles two rooms`);
      if (seen[k]) bad(`${key}: ${it.t} sits on ${seen[k]} at ${k}`);
      seen[k] = it.t;
    }
  }
}

const MON = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
let prev = null;
PUZZLES.forEach((p, i) => {
  const tag = `#${p.num} ${p.live}`;
  if (p.num !== i + 1) bad(`${tag}: num out of order`);
  const d = new Date(p.live + 'T12:00:00Z');
  if (prev && (d - prev) !== 86400000) bad(`${tag}: not the day after the previous board`);
  prev = d;
  const want = `sudoclue-${d.getUTCMonth() + 1}-${d.getUTCDate()}-${String(d.getUTCFullYear()).slice(2)}`;
  if (p.quizId !== want) bad(`${tag}: quizId ${p.quizId}, expected ${want}`);
  if (p.dateLabel !== `${MON[d.getUTCMonth()]} ${d.getUTCDate()}, ${d.getUTCFullYear()}`) bad(`${tag}: dateLabel ${p.dateLabel}`);
  const L = PLACES[p.place];
  if (!L) { bad(`${tag}: unknown place ${p.place}`); return; }
  const N = L.rooms.length;
  if (p.cast.length !== N || new Set(p.cast).size !== N) bad(`${tag}: cast is not ${N} distinct names`);
  for (const c of p.cast) if (!CAST[c]) bad(`${tag}: ${c} has no portrait`);
  for (const c of p.clues) {
    if (!KINDS.has(c.k)) bad(`${tag}: unknown clue kind ${c.k}`);
    if (!c.text || /[—]/.test(c.text)) bad(`${tag}: clue text missing or carries an em dash`);
    for (const who of [c.p, c.q]) if (who && !p.cast.includes(who)) bad(`${tag}: clue names ${who}, not in the cast`);
  }
  const t0 = Date.now();
  const opt = { three: !!p.three };
  if (p.num >= THREE_FROM && !p.three) bad(`${tag}: from No. ${THREE_FROM} a board must be a three-role board`);
  if (p.num < THREE_FROM && p.three) bad(`${tag}: went live before three roles, must stay as it was`);
  const sols = solve(L, p.cast, p.clues, 2, opt);
  if (sols.length !== 1) { bad(`${tag}: ${sols.length} answers (need exactly 1)`); return; }
  // The two stages stand on their own: placement clues alone fix the board, role clues alone fix the roles.
  const pl = solvePlacement(L, p.cast, p.clues, 2);
  if (pl.length !== 1) bad(`${tag}: placement clues allow ${pl.length} boards (need exactly 1)`);
  const rl = solveRoles(L, p.cast, sols[0].place, p.clues, 2, opt);
  if (p.three) {
    if (p.clues.some((c) => c.k === 'isrole')) bad(`${tag}: a note names someone's role outright`);
    const gro = gradeRoles(L, p.cast, sols[0].place, p.clues);
    if (!gro.solved) bad(`${tag}: the notes need a guess`);
    if (gro.firstPin) bad(`${tag}: one note alone names someone`);
  }
  if (rl.length !== 1) bad(`${tag}: role clues allow ${rl.length} role sets on the board (need exactly 1)`);
  const per = {};
  for (const c of p.clues) if (c.p && !isRoleClue(c)) per[c.p] = (per[c.p] || 0) + 1;
  if (Object.values(per).some((n) => n > (N <= 8 ? 1 : 2))) bad(`${tag}: a person has more than ${N <= 8 ? 1 : 2} placement clues`);
  // THE DAY'S BAND (owner, 2026-11-02): from No. 5 (Tue Nov 3) a board's hardest move must sit in its day's band
  // and no board may need a guess. Earlier boards went live before the rule and are reported, not failed.
  const gr = gradePlacement(L, p.cast, p.clues); const band = d.getUTCDay() === 3 && d < new Date(Date.UTC(2026, 10, 5)) ? [2, 3] : DAY_BAND[d.getUTCDay()]; // WED_WAS: Wednesdays before Nov 5
  const fits = gr.rank >= band[0] && gr.rank <= band[1];
  if (p.num >= GRADED_FROM && !fits) bad(`${tag}: grade ${gr.rank} (${gr.whatifs} what-if) is outside its day's band ${band[0]}-${band[1]}`);
  if (pl.length === 1 && rl.length === 1) console.log(`✓ ${tag} ${L.title} ${N}x${N}, ${p.clues.length} clues, unique in both stages, grade ${gr.rank}${fits ? '' : p.num >= GRADED_FROM ? '' : ' (pre-rule)'} (${Date.now() - t0}ms)`);
});
console.log(fail ? `${fail} failed` : `all ${PUZZLES.length} Sudoclue cases verified`);
process.exit(fail ? 1 : 0);
