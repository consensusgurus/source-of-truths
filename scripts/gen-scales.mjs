// gen-scales: builds the Scales bank (app/scales/puzzles.js), one board a day
// from 2026-11-26. APPEND ONLY: boards already in the file are kept byte for
// byte and only dates after the last one are added, so a live board can never
// move (docs/claude/daily-authoring.md, "The past is frozen").
//
//   node scripts/gen-scales.mjs --through 2027-03-31
//
// A board is lib/scales-engine.js buildBoard(seed, band): the band comes from
// the weekday (Mon/Tue gentle, Wed to Fri moderate, Sat tough, Sun the Sunday
// Edition), the seed from the date. A seed that gives no board inside its try
// budget is skipped for the next one, and the seed used is stored on the board,
// so the checker rebuilds every board from it and fails on any hand edit.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { buildBoard, bandOf } from '../lib/scales-engine.js';

export const FIRST = '2026-11-26';
const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
const here = dirname(fileURLToPath(import.meta.url));
const FILE = join(here, '..', 'app', 'scales', 'puzzles.js');

export function baseSeed(live) {
  let h = 2166136261;
  for (const c of `scales:${live}`) { h ^= c.charCodeAt(0); h = Math.imul(h, 16777619) >>> 0; }
  return h >>> 0;
}
export function boardFor(live) {
  const band = bandOf(live);
  for (let k = 0; k < 200; k++) {
    const seed = (baseSeed(live) + k * 7919) >>> 0;
    const b = buildBoard(seed, band);
    if (b) return { band, seed, ...b };
  }
  throw new Error(`no seed gives a board for ${live}`);
}

const HEADER = `// Puzzle data for Scales, the daily balance-scale weights puzzle (owner,
// 2026-11-26). Imported ONLY by the server page (app/scales/page.js), which
// filters live<=today before handing boards to the client.
//
// GENERATED by scripts/gen-scales.mjs. Never hand-edit a board and never
// regenerate one that has gone live: the generator only appends days, and
// scripts/verify-scales.mjs rebuilds every board from its stored seed and
// proves again that it has exactly one answer.
//
// A board: n shapes ('a' circle, 'b' triangle, 'c' square, 'd' diamond,
// 'e' hexagon, 'f' star, the first n of them), max (every shape weighs 1 to
// max), sol (the weights, in that order) and scales. A scale is L and R, the
// two arms, each a list of shape letters and numbers (a number is a numbered
// weight), and t: '=' balanced, '>' the left arm is heavier, '<' the right is.
// band is the weekday's ramp: gentle, moderate, tough or sunday.
export const PUZZLES = [
`;

function fmtBoard(p) { return '  ' + JSON.stringify(p) + ','; }

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const i = process.argv.indexOf('--through');
  const through = i > 0 ? process.argv[i + 1] : null;
  if (!/^\d{4}-\d{2}-\d{2}$/.test(through || '')) { console.error('usage: node scripts/gen-scales.mjs --through YYYY-MM-DD'); process.exit(1); }
  let lines = [], last = null, num = 0;
  if (existsSync(FILE)) {
    const src = readFileSync(FILE, 'utf8');
    lines = src.split('\n').filter((l) => l.startsWith('  {"num"'));
    for (const l of lines) { const p = JSON.parse(l.trim().replace(/,$/, '')); last = p.live; num = p.num; }
  }
  let day = new Date(`${last || FIRST}T12:00:00Z`);
  if (last) day = new Date(day.getTime() + 86400000);
  let added = 0;
  while (day.toISOString().slice(0, 10) <= through) {
    const live = day.toISOString().slice(0, 10);
    const [y, m, d] = live.split('-').map(Number);
    const b = boardFor(live);
    num += 1;
    lines.push(fmtBoard({ num, quizId: `scales-${m}-${d}-${String(y).slice(2)}`, live, dateLabel: `${MONTHS[m - 1]} ${d}, ${y}`, sunday: b.band === 'sunday', band: b.band, seed: b.seed, n: b.n, max: b.max, sol: b.sol, scales: b.scales }));
    added++;
    day = new Date(day.getTime() + 86400000);
  }
  writeFileSync(FILE, HEADER + lines.join('\n') + '\n];\n');
  console.log(`gen-scales: ${added} boards added, ${lines.length} in the bank`);
}
