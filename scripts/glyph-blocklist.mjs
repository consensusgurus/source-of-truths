export const GLYPH_BLOCK = new Set(LIST.split(/\s+/).filter(Boolean));

// Three-letter words dropped from the generator's curated THREE list for the
// same reasons (it is matched against the same set, so they live here too).
for (const w of ['GUN', 'ZIT', 'BRA', 'BUM']) GLYPH_BLOCK.add(w);

export function isGlyphBlocked(word) {
  const w = word.toUpperCase();
  return GLYPH_BLOCK.has(w) || GLYPH_BLOCK_STEMS.some((st) => w.includes(st));
}
