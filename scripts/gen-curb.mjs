// gen-curb: builds the Curb bank (app/curb/puzzles.js), one day from
// 2026-11-28. APPEND ONLY: days already in the file are kept byte for byte and
// only dates after the last one are added, so a live board can never move
// (docs/claude/daily-authoring.md, "The past is frozen").
//
//   node scripts/gen-curb.mjs --through 2027-02-28
//
// A day is lib/curb-engine.js daySettings(seed, band, live): the band comes
// from the weekday (Mon/Tue Gentle, Wed to Fri Moderate, Sat Tough, Sun the
// truck), the seed from the date. A seed is kept only if the planner can park
// it (plan() finds a path); otherwise the next seed is tried. The seed used is
// stored, so the checker rebuilds every day from it.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { bandOf, daySettings, buildDay, plan } from '../lib/curb-engine.js';

export const FIRST = '2026-11-28';
const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
const here = dirname(fileURLToPath(import.meta.url));
const FILE = join(here, '..', 'app', 'curb', 'puzzles.js');
export const PLAN_NODES = { car: 400000, truck: 500000 };

export function baseSeed(live) {
  let h = 2166136261;
  for (const c of `curb:${live}`) { h ^= c.charCodeAt(0); h = Math.imul(h, 16777619) >>> 0; }
  return h >>> 0;
}
export function dayFor(live) {
  const band = bandOf(live);
  for (let k = 0; k < 40; k++) {
    const seed = (baseSeed(live) + k * 7919) >>> 0;
    const set = daySettings(seed, band, live);
    const r = plan(buildDay(set), { maxNodes: PLAN_NODES[set.kind] });
    if (r.found) return { band, seed, set, moves: r.moves.length };
  }
  throw new Error(`no seed gives a parkable day for ${live}`);
}

const HEADER = `// Puzzle data for Curb, the daily parking puzzle (owner, 2026-11-28).
// Imported ONLY by the server page (app/curb/page.js), which filters
// live<=today before handing days to the client.
//
// GENERATED by scripts/gen-curb.mjs. Never hand-edit a day and never
// regenerate one that has gone live: the generator only appends days, and
// scripts/verify-curb.mjs rebuilds every day from its stored seed and proves
// again that it can be parked.
//
// set is everything the board is built from (lib/curb-engine.js buildDay).
// A car day: car, spare (metres of room beyond the car's length), side ('R'
// curb on the right, 'L' on the left), ahead and behind (the parked
// neighbours' lengths), hydrant (null, 'front' or 'back': red curb you may
// not park beside), traffic (a car comes up the lane behind you), scene. A
// truck day (Sunday): trailer ('long' 53 ft or 'pup' 28 ft), cab ('day' or
// 'sleeper'), from ('L' or 'R'), target (bay index 0..5), scene.
export const PUZZLES = [
`;

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const i = process.argv.indexOf('--through');
  const through = i > 0 ? process.argv[i + 1] : null;
  if (!/^\d{4}-\d{2}-\d{2}$/.test(through || '')) { console.error('usage: node scripts/gen-curb.mjs --through YYYY-MM-DD'); process.exit(1); }
  let lines = [], last = null, num = 0;
  if (existsSync(FILE)) {
    const src = readFileSync(FILE, 'utf8');
    lines = src.split('\n').filter((l) => l.startsWith('  {"num"'));
    for (const l of lines) { const p = JSON.parse(l.trim().replace(/,$/, '')); last = p.live; num = p.num; }
  }
  let day = new Date(`${last || FIRST}T12:00:00Z`);
  if (last) day = new Date(day.getTime() + 86400000);
  let added = 0;
  while (day.toISOString().slice(0, 10) <= through) {
    const live = day.toISOString().slice(0, 10);
    const [y, m, d] = live.split('-').map(Number);
    const b = dayFor(live);
    num += 1;
    lines.push('  ' + JSON.stringify({ num, quizId: `curb-${m}-${d}-${String(y).slice(2)}`, live, dateLabel: `${MONTHS[m - 1]} ${d}, ${y}`, sunday: b.band === 'sunday', band: b.band, seed: b.seed, set: b.set }) + ',');
    added++;
    process.stdout.write(`${live} ${b.band} ${b.set.kind === 'car' ? b.set.car : b.set.trailer} (${b.moves} arcs)\n`);
    day = new Date(day.getTime() + 86400000);
  }
  writeFileSync(FILE, HEADER + lines.join('\n') + '\n];\n');
  console.log(`gen-curb: ${added} days added, ${lines.length} in the bank`);
}
