// Freeze the CURRENT college football board into lib/gridiron-archive.js.
//
// Run this at the START of every weekly CFB refresh, before lib/gridiron-data.js
// is touched: it copies the block that is live right now, as published, into the
// archive the week switcher reads, together with the order and ratings the engine
// gives it today. Then refresh the live block as usual.
//
//   node scripts/archive-cfb-week.mjs          append the live week (no-op if archived)
//   node scripts/archive-cfb-week.mjs --check  exit 1 if the live week is NOT archived
//
// The past is frozen (CLAUDE-RANKINGS.md §0 rule 5), so an entry is never
// rewritten: re-running on an already archived week changes nothing, and
// scripts/verify-gridiron-archive.mjs fails if today's engine stops reproducing
// any archived board exactly.
import fs from 'node:fs';
import path from 'node:path';
import { register } from 'node:module';
import { fileURLToPath } from 'node:url';

register('./alias-loader.mjs', import.meta.url);
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FILE = path.join(ROOT, 'lib/gridiron-archive.js');

const HEADER = `// Past college football boards, frozen as published, for the week switcher on
// /collegefootballrankings (owner request, 2026-09-27).
//
// GENERATED by scripts/archive-cfb-week.mjs. Do not edit by hand: an entry is the
// live block exactly as it stood when that week was replaced, plus \`published\`,
// the [team, rank, rating] order the engine gave it. The page recomputes each
// board with today's engine, so scripts/verify-gridiron-archive.mjs asserts that
// recomputation still matches \`published\` to the second decimal. If a scoring
// change ever breaks that, the change is rewriting history: gate it by date
// rather than regenerating this file (the past is frozen, CLAUDE-RANKINGS.md §0).
//
// Starts at week 2, the first board built on completed games. The week 1 board
// (preseason plus Thursday's games, 2026-09-04) was scored by an earlier engine
// that today's does not reproduce, so it is not archived rather than shown wrong.
//
// \`week\` is the board's own week label (the ESPN week whose games were next),
// the same number the live page prints in "week N · built <date>".
`;

export function serialize(entries) {
  const rows = entries
    .slice()
    .sort((a, b) => a.week - b.week)
    .map((e) => '  ' + JSON.stringify(e) + ',');
  return HEADER + '\nexport const CFB_ARCHIVE = [\n' + rows.join('\n') + '\n];\n';
}

export async function publishedOrder(block) {
  const { computeComposite } = await import('../lib/gridiron.js');
  const out = computeComposite(block, 'cfb', { fetchedAt: block.builtAt });
  return out.ranked.map((r) => [r.team, r.rank, +r.score.toFixed(2)]);
}

async function main() {
  const { GRIDIRON } = await import('../lib/gridiron-data.js');
  const { CFB_ARCHIVE } = await import('../lib/gridiron-archive.js');
  const live = structuredClone(GRIDIRON.cfb);
  live.builtAt = live.builtAt || GRIDIRON.fetchedAt;
  const have = CFB_ARCHIVE.some((e) => e.week === live.week);
  if (process.argv.includes('--check')) {
    console.log(have ? `week ${live.week} is archived` : `week ${live.week} is NOT archived`);
    process.exit(have ? 0 : 1);
  }
  if (have) {
    console.log(`week ${live.week} is already archived; nothing to do`);
    return;
  }
  const entry = { week: live.week, builtAt: live.builtAt, published: await publishedOrder(live), block: live };
  fs.writeFileSync(FILE, serialize([...CFB_ARCHIVE, entry]));
  console.log(`archived week ${live.week} (built ${live.builtAt}); ${CFB_ARCHIVE.length + 1} weeks in the archive`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) await main();
