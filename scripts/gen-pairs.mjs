// scripts/gen-pairs.mjs: deals Pairs' bank into app/pairs/puzzles.js.
//
//   node scripts/gen-pairs.mjs                     # 2026-11-01 .. --until
//   node scripts/gen-pairs.mjs --until 2027-01-31  # EXTEND: rows already in the
//                                                  # bank are kept byte for byte
//
// Pairs is the daily game of Concentration, played with real playing cards: the
// whole deal face down, turn two at a time, and a pair is two cards of the SAME
// RANK AND COLOUR (the seven of hearts with the seven of diamonds, the queen of
// spades with the queen of clubs). Nothing is authored; the deal is shuffled.
//
// THE SIZE (owner, 2026-11-01: "bigger / harder even on easy days"):
//   every day   36 cards, 18 pairs, a 6x6 table
//   Sunday      48 cards, 24 pairs, an 8x6 table (the Sunday Edition)
// Same rank in the other colour is the trap: the seven of spades is not the
// seven of hearts' pair. Every deal carries at least four such near misses.
//
// `deal` is the table read row by row, encoded so the faces are not readable at a
// glance in the page source: card i is DECK[(code - 7 * i - salt) mod 52] where
// code is the base-36 pair of characters at 2i, DECK is the 52-card order below
// and salt is the row's num. scripts/verify-pairs.mjs decodes and re-checks it.
//   cols x rows  the table (6x6, or 8x6 on Sundays)
//
// Deterministic: same seed, same bank.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'app', 'pairs', 'puzzles.js');
const args = process.argv.slice(2);
const opt = (k, d) => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : d; };
const START = '2026-11-01';
const UNTIL = opt('--until', '2027-01-31');

export const RANKS = ['A', '2', '3', '4', '5', '6', '7', '8', '9', 'T', 'J', 'Q', 'K'];
export const SUITS = ['S', 'H', 'D', 'C'];
export const DECK = RANKS.flatMap((r) => SUITS.map((s) => r + s));
const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
function days(from, to) { const o = []; for (let t = Date.parse(from + 'T12:00:00Z'); t <= Date.parse(to + 'T12:00:00Z'); t += 86400000) o.push(new Date(t).toISOString().slice(0, 10)); return o; }
const dow = (iso) => new Date(iso + 'T12:00:00Z').getUTCDay();
const label = (iso) => { const [y, m, d] = iso.split('-').map(Number); return `${MONTHS[m - 1]} ${d}, ${y}`; };
const qid = (iso) => { const [y, m, d] = iso.split('-').map(Number); return `pairs-${m}-${d}-${String(y).slice(2)}`; };
function rng(seed) { let s = seed >>> 0; return () => { s = (s + 0x6D2B79F5) >>> 0; let t = s; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }; }
function shuffle(a, r) { for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(r() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; }
export function encode(cards, salt) { return cards.map((c, i) => (((DECK.indexOf(c) + 7 * i + salt) % 52 + 52) % 52).toString(36).padStart(2, '0')).join(''); }

if (process.argv[1] && process.argv[1].endsWith('gen-pairs.mjs')) {
  let kept = [];
  if (fs.existsSync(OUT)) kept = fs.readFileSync(OUT, 'utf8').split('\n').filter((l) => l.startsWith('  {"num"')).map((l) => JSON.parse(l.trim().replace(/,$/, '')));
  const have = new Set(kept.map((p) => p.live));
  const rows = [...kept];
  for (const d of days(START, UNTIL)) {
    if (have.has(d)) continue;
    const num = rows.length + 1, sun = dow(d) === 0;
    const cols = sun ? 8 : 6, nrows = 6, pairs = (cols * nrows) / 2;
    const r = rng(20261101 + num * 7919);
    let cards;
    for (;;) {
      // the 26 possible pairs: a rank in red (hearts + diamonds) or black (spades + clubs)
      const kinds = shuffle(RANKS.flatMap((k) => [[k, 'r'], [k, 'b']]), r).slice(0, pairs);
      // near misses: ranks dealt in BOTH colours
      const both = RANKS.filter((k) => kinds.some((x) => x[0] === k && x[1] === 'r') && kinds.some((x) => x[0] === k && x[1] === 'b')).length;
      if (both < 4) continue;
      cards = shuffle(kinds.flatMap(([k, c]) => (c === 'r' ? [k + 'H', k + 'D'] : [k + 'S', k + 'C'])), r);
      break;
    }
    rows.push({ num, quizId: qid(d), live: d, dateLabel: label(d), ...(sun ? { sunday: true } : {}), cols, rows: nrows, deal: encode(cards, num) });
  }
  const head = `// Puzzle data for Pairs, the daily game of Concentration with playing cards.
// GENERATED by scripts/gen-pairs.mjs; do not edit by hand. Extend with
// \`node scripts/gen-pairs.mjs --until <date>\`, which keeps every row here byte
// for byte. Checked by scripts/verify-pairs.mjs. Imported only by the server page,
// which strips days not yet live. The deal encoding is in the generator's header.
export const PUZZLES = [
`;
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, head + rows.map((p) => '  ' + JSON.stringify(p) + ',').join('\n') + '\n];\n');
  console.log(`pairs: ${rows.length} rows`);
}
