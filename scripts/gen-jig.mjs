// scripts/gen-jig.mjs: deals the Jig bank (app/jig/puzzles.js) from the photo
// pool in scripts/jig-photos.mjs, one photo a day from LAUNCH.
//
//   node scripts/gen-jig.mjs
//
// The cut is a property of the weekday (owner, 2026-10-15: capped at 80, the
// week kept close to it): Mon 8x6 = 48, Tue 9x6 = 54, Wed 10x6 = 60,
// Thu 9x7 = 63, Fri 10x7 = 70, Sat 11x7 = 77, and the Sunday Edition 10x8 = 80.
// The tab pattern is drawn by the client from `seed`, so a board is fully
// described by its photo, its grid and its seed.
//
// The deal is deterministic from the pool's ORDER, so to extend the bank add
// photos at the END of scripts/jig-photos.mjs: every day already dealt comes
// out byte for byte the same. Never reorder or remove a row that has gone live.
import fs from 'fs';
import { PHOTOS } from './jig-photos.mjs';

const LAUNCH = '2026-10-15';
const CUT = { 1: [8, 6], 2: [9, 6], 3: [10, 6], 4: [9, 7], 5: [10, 7], 6: [11, 7], 0: [10, 8] };
const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

const rows = [];
const d0 = new Date(LAUNCH + 'T12:00:00Z');
PHOTOS.forEach((p, i) => {
  const d = new Date(d0.getTime() + i * 86400000);
  const iso = d.toISOString().slice(0, 10);
  const dow = d.getUTCDay();
  const [cols, rows_] = CUT[dow];
  const num = i + 1;
  rows.push({
    num,
    quizId: `jig-${d.getUTCMonth() + 1}-${d.getUTCDate()}-${String(d.getUTCFullYear()).slice(2)}`,
    live: iso,
    dateLabel: `${MONTHS[d.getUTCMonth()]} ${d.getUTCDate()}, ${d.getUTCFullYear()}`,
    sunday: dow === 0,
    cols, rows: rows_,
    seed: (num * 7919 + 13) % 100003,
    t: p.t, name: p.name, lic: p.lic, by: p.by,
  });
});

const head = `// Puzzle data for Jig, the daily jigsaw. Generated by scripts/gen-jig.mjs from
// scripts/jig-photos.mjs; do not hand edit. One Wikimedia Commons featured
// picture a day: \`t\` is the Commons file title (fetched only through
// /api/jig/img, which refuses a day not yet live), \`name\`, \`lic\` and \`by\` are
// printed on the finish card, \`cols\` x \`rows\` is the cut and \`seed\` draws
// the tabs. The shared daily consumers read num/quizId/live/dateLabel/sunday.
// The server page strips future days, so tomorrow's photo never reaches a
// browser.
export const PUZZLES = [
`;
fs.writeFileSync('app/jig/puzzles.js', head + rows.map((r) => '  ' + JSON.stringify(r) + ',').join('\n') + '\n];\n');
console.log(`gen-jig: ${rows.length} boards, ${rows[0].live} to ${rows[rows.length - 1].live}`);
