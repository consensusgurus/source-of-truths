// scripts/gen-tangled.mjs — writes app/tangled/puzzles.js.
//
// One board a day, made by lib/tangled-engine.js generate() off the date: the
// frame shape cycles by day of the year, the rope count by weekday (Mon 4, Tue
// and Wed 5, Thu and Fri 6, Sat 7, Sun 8). Deterministic: re-running it on an
// unchanged calendar is byte-identical, and it never renumbers.
//
//   node scripts/gen-tangled.mjs > app/tangled/puzzles.js
import { generate, dayParams, quizIdFor, seedFor, pegColours } from '../lib/tangled-engine.js';

const FIRST = '2026-11-07';
const LAST = process.argv[2] || '2027-01-31';
const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
const rows = [];
let d = new Date(FIRST + 'T12:00:00Z');
const end = new Date(LAST + 'T12:00:00Z');
let num = 1;
while (d <= end) {
  const y = d.getUTCFullYear(), m = d.getUTCMonth() + 1, day = d.getUTCDate();
  const live = `${y}-${String(m).padStart(2, '0')}-${String(day).padStart(2, '0')}`;
  const { shape, R, dow } = dayParams(live);
  const seed = seedFor(live, shape);
  const b = generate(seed, R, shape);
  const J = (a) => JSON.stringify(a);
  rows.push(`  { num: ${num}, quizId: '${quizIdFor(live)}', live: '${live}', dateLabel: '${MONTHS[m - 1]} ${day}, ${y}', sunday: ${dow === 0}, shape: '${shape}', R: ${R}, H: ${b.H}, ropes: ${J(b.ropes)}, solved: ${J(b.solved)}, pegs: ${J(pegColours(seed, R))} },`);
  num++;
  d = new Date(d.getTime() + 86400000);
}

process.stdout.write(`// Puzzle data for Tangled, the daily rope untangling puzzle. GENERATED by
// scripts/gen-tangled.mjs (lib/tangled-engine.js); do not edit a board by hand.
// Imported ONLY by the server page (app/tangled/page.js), which filters
// live<=today before handing the bank to the client.
//
// Fields:
//   shape   the frame: circle, hexagon, square, triangle, rectangle, diamond, pentagon
//   R, H    ropes, and holes round the edge (always R*2 + 2: two empty holes)
//   ropes   the starting board, one [hole, hole] pair per rope
//   solved  the untangled board it was scrambled from (Give up eases back to it;
//           any board with no crossing ropes is a solve, not only this one)
//   pegs    the two peg colours per rope (indices into PEG_PASTELS), never equal
//   sunday  a real Sunday: the biggest board of the week (eight ropes), no
//           separate Edition
// scripts/verify-tangled.mjs checks every row.
export const PUZZLES = [
${rows.join('\n')}
];
`);
