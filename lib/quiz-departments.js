export function quizDept(q) {
  if (!q) return 'misc';
  if (QUIZ_DEPT[q.id]) return QUIZ_DEPT[q.id];
  let id = q.id || '';
  if (q.format === 'map' || q.format === 'place-map' || q.format === 'globe' || q.format === 'geo-aerial') return 'geography';
  // A "-typed" (or other future suffix) variant inherits its base quiz's department.
  const baseId = id.replace(/-typed$/, '');
  if (baseId !== id && QUIZ_DEPT[baseId]) return QUIZ_DEPT[baseId];
  id = baseId;
  if (/sports?|nfl|nba|mlb|nhl|fifa|olympic|super-bowl|world-cup|athlete|grand-slam|soccer|golf|tennis|\bf1\b|f1-|college-football|college-basketball|ncaa|stanley-cup|world-series/.test(id)) return 'sports';
  if (q.type === 'travel') return 'travel';
  if (/film|movie|box-office|director|actor|animated|oscar/.test(id)) return 'movies';
  if (/games|video-games|game-console|game-franchise/.test(id)) return 'gaming';
  if (/song|album|single|spotify|music-video|concert-tour|billboard|soundtrack|music-artist/.test(id)) return 'music';
  if (/book|novel|author|opening-lines/.test(id)) return 'literature';
  if (/youtube|instagram|broadway|emmy|netflix|standup/.test(id)) return 'entertainment';
  if (/cookie|chips|sandwich|pizza|sub-chain|menu-item|restaurant-chain|\bfood\b/.test(id)) return 'food';
  if (/\bcars?\b|endowment|compan|slogan|brand|business|earnings|market-news|daily-market/.test(id)) return 'business';
  if (/animal|language/.test(id)) return 'science';
  // No blanket type:'other' -> geography fallback (it silently mislabeled many
  // non-geography quizzes). Unknown ids fall through to 'misc'; add new quizzes
  // to QUIZ_DEPT above so they never rely on this heuristic.
  if (/paint|artwork|masterpiece|sculpture/.test(id)) return 'arts';
  if (/phobia/.test(id)) return 'science';
  if (/president|election|emperor|\bcaesar\b|dynasty|monarch|civil-war/.test(id)) return 'history';
  // Reclassified out of Miscellaneous (owner request, July 2026): the "closest
  // countries to X" and "higher or lower" families are geography; planet/moon
  // magnitude quizzes go to science.
  if (/^closest-countries-to/.test(id)) return 'geography';
  if (/^higher-or-lower-/.test(id)) return /planet|moon/.test(id) ? 'science' : 'geography';
  // Last resort before 'misc': honor the quiz's own category label if it maps
  // cleanly to a real department (see CATEGORY_DEPT). Stops a new quiz with a
  // real category from silently landing in the deprecated Miscellaneous bucket
  // when nobody remembered to add a QUIZ_DEPT entry.
  if (q.category && CATEGORY_DEPT[q.category]) return CATEGORY_DEPT[q.category];
  return 'misc';
}

